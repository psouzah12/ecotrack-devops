CREATE TABLE TB_EMPRESA (
    ID_EMPRESA NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME VARCHAR2(150) NOT NULL,
    CNPJ VARCHAR2(18) NOT NULL UNIQUE,
    SETOR VARCHAR2(100) NOT NULL,
    CIDADE VARCHAR2(100) NOT NULL,
    ESTADO VARCHAR2(2) NOT NULL,
    DATA_CADASTRO DATE DEFAULT SYSDATE NOT NULL
);

CREATE TABLE TB_INDICADOR_ESG (
    ID_INDICADOR NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_EMPRESA NUMBER NOT NULL,
    TIPO VARCHAR2(50) NOT NULL,
    VALOR NUMBER(12,2) NOT NULL,
    UNIDADE_MEDIDA VARCHAR2(30) NOT NULL,
    DATA_REFERENCIA DATE NOT NULL,
    OBSERVACAO VARCHAR2(255),
    CONSTRAINT FK_INDICADOR_EMPRESA
        FOREIGN KEY (ID_EMPRESA)
        REFERENCES TB_EMPRESA(ID_EMPRESA)
);

CREATE TABLE TB_ACAO_ESG (
    ID_ACAO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_EMPRESA NUMBER NOT NULL,
    TITULO VARCHAR2(150) NOT NULL,
    DESCRICAO VARCHAR2(500) NOT NULL,
    CATEGORIA VARCHAR2(80) NOT NULL,
    STATUS VARCHAR2(50) NOT NULL,
    IMPACTO_ESTIMADO NUMBER(12,2),
    DATA_INICIO DATE NOT NULL,
    DATA_FIM_PREVISTA DATE,
    CONSTRAINT FK_ACAO_EMPRESA
        FOREIGN KEY (ID_EMPRESA)
        REFERENCES TB_EMPRESA(ID_EMPRESA)
);
